CREATE TABLE route_details (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,

    route_id bigint NOT NULL,

    geometry text NOT NULL,
    geometry_precision integer NOT NULL,

    distance_meters double precision NOT NULL,
    duration_seconds double precision NOT NULL,

    segment_distances double precision[] NOT NULL,
    segment_durations double precision[] NOT NULL,

    CONSTRAINT route_details_route_uk UNIQUE (route_id),
    CONSTRAINT route_details_route_fk
        FOREIGN KEY (route_id)
            REFERENCES route (id)
);
