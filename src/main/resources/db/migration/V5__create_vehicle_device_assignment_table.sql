CREATE TABLE vehicle_device_assignment (
                                           id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                           created_at timestamp(6) with time zone NOT NULL,
                                           updated_at timestamp(6) with time zone,
                                           deleted_at timestamp(6) with time zone,

                                           vehicle_id bigint,
                                           device_id bigint,

                                           assigned_by bigint NOT NULL,


                                           CONSTRAINT vehicle_driver_assignment_vehicle_fk
                                               FOREIGN KEY (vehicle_id)
                                                   REFERENCES vehicle (id),

                                           CONSTRAINT vehicle_device_assignment_driver_fk
                                               FOREIGN KEY (device_id)
                                                   REFERENCES tracking_device (id),

                                           CONSTRAINT vehicle_device_assignment_assigned_by_fk
                                               FOREIGN KEY (assigned_by)
                                                   REFERENCES app_user (id)
);